-- Sales aggregation CTE by product and branch
WITH sales AS (
    SELECT 
        [SOL].[C_SPECIALPRODUCT] AS C_ID,
        SUM([SOL].[C_QUANTITY]) AS [QTYOrdered],
        SUM(CASE WHEN sol.C_FULFILLMENTMETHOD = 0 THEN sol.C_QUANTITYSUPPLIED ELSE 0 END) AS [QTYSupplied],
        SUM(CASE WHEN sol.C_FULFILLMENTMETHOD = 0 THEN [SOL].[C_QUANTITYOUTSTANDING] ELSE 0 END) AS [QTYOustanding],
        SUM(SOL.C_NETPRICE - (SOL.C_DISCOUNTAMOUNT / NULLIF([SOL].[C_QUANTITY], 0))) AS [NetPriceSum],
        SUM(CASE WHEN sol.C_FULFILLMENTMETHOD = 1 THEN sol.C_QUANTITYSUPPLIED ELSE 0 END) AS Direct,
        br.C_ID AS BranchID
    FROM [dbo].[T_SALESORDER_LINE] AS [SOL] WITH (NOLOCK)
    JOIN [dbo].[T_SALESORDER] AS [SO] WITH (NOLOCK) ON [SOL].[C__OWNER_] = [SO].[C_ID]
    JOIN [dbo].[T_BRANCH] AS [BR] WITH (NOLOCK) ON [br].[C_ID] = [so].[C_BRANCH]
    WHERE [SOL].[C_SPECIALPRODUCT] IS NOT NULL
    GROUP BY [SOL].[C_SPECIALPRODUCT], br.C_ID
),
-- Purchase orders aggregation CTE
PO AS (
    SELECT 
        [POL].[C_SPECIALPRODUCT] AS C_ID,
        SUM([POL].[C_QUANTITY]) AS [QTYOrdered],
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 0 THEN pol.[C_QUANTITYSUPPLIED] ELSE 0 END) AS [QTYSupplied],
        SUM([POL].[C_QUANTITYWRITTENOFF]) AS [QTYWrittenOff],
        SUM([POL].[C_QUANTITYOUTSTANDING]) AS [QTYOustanding],
        SUM(IIF(POL.C_DISCOUNTAMOUNT = 0, POL.C_NETPRICE, (POL.C_DISCOUNTAMOUNT / NULLIF([POL].[C_QUANTITY], 0)))) AS [NetPriceSum],
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 1 THEN pol.[C_QUANTITYSUPPLIED] ELSE 0 END) AS Direct,
        po.C_DELIVERTOBRANCH AS BranchID
    FROM [dbo].[T_PURCHASEORDER_LINE] AS [POL] WITH (NOLOCK)
    JOIN [dbo].[T_PURCHASEORDER] AS [PO] WITH (NOLOCK) ON [POL].[C__OWNER_] = [PO].[C_ID]
    WHERE [POL].[C_SPECIALPRODUCT] IS NOT NULL
    GROUP BY [POL].[C_SPECIALPRODUCT], po.C_DELIVERTOBRANCH
),
-- Sales credit requests aggregation CTE
CR AS (
    SELECT 
        [POL].[C_SPECIALPRODUCT] AS C_ID,
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 1 THEN [POL].[C_QUANTITY] ELSE 0 END) AS Direct_QTY_CR,
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 0 THEN [POL].[C_QUANTITY] ELSE 0 END) AS [QTY_CR],
        po.C_BRANCH AS BranchID
    FROM [dbo].[T_SALESCREDITREQUEST_LINE] AS [POL] WITH (NOLOCK)
    JOIN [dbo].[T_SALESCREDITREQUEST] AS [PO] WITH (NOLOCK) ON [POL].[C__OWNER_] = [PO].[C_ID]
    WHERE [POL].[C_SPECIALPRODUCT] IS NOT NULL
    GROUP BY [POL].[C_SPECIALPRODUCT], po.C_BRANCH
),
-- Sales credit notes aggregation CTE
CRN AS (
    SELECT 
        [POL].[C_SPECIALPRODUCT] AS C_ID,
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 1 THEN [POL].[C_QUANTITY] ELSE 0 END) AS Direct_QTY_CN,
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 0 THEN [POL].[C_QUANTITY] ELSE 0 END) AS [QTY_CN],
        po.C_BRANCH AS BranchID
    FROM [dbo].[T_SALESCREDITNOTE_LINE] AS [POL] WITH (NOLOCK)
    JOIN [dbo].[T_SALESCREDITNOTE] AS [PO] WITH (NOLOCK) ON [POL].[C__OWNER_] = [PO].[C_ID]
    WHERE [POL].[C_SPECIALPRODUCT] IS NOT NULL
    GROUP BY [POL].[C_SPECIALPRODUCT], po.C_BRANCH
),
-- Purchase credit requests aggregation CTE
PR AS (
    SELECT 
        [POL].[C_SPECIALPRODUCT] AS C_ID,
        SUM(CASE WHEN pol.C_FULFILLMENTMETHOD = 1 THEN [POL].[C_QUANTITYINSTOCKINGUNITS] ELSE 0 END) AS Direct_QTY_PR,
        SUM(CASE WHEN pol.C_QUANTITYINSTOCKINGUNITS = 0 THEN 0 ELSE [POL].[C_QUANTITYINSTOCKINGUNITS] END) AS [QTY_PR],
        po.C_BRANCH AS BranchID
    FROM [dbo].[T_PURCHASECREDITREQUEST_LINE] AS [POL] WITH (NOLOCK)
    JOIN [dbo].[T_PURCHASECREDITREQUEST] AS [PO] WITH (NOLOCK) ON [POL].[C__OWNER_] = [PO].[C_ID]
    WHERE C_STOCKADJUSTMENTMETHOD = 1 AND [POL].[C_SPECIALPRODUCT] IS NOT NULL
    GROUP BY [POL].[C_SPECIALPRODUCT], po.C_BRANCH
),
-- Stock movements aggregation CTE
Smove AS (
    SELECT 
        sml.C_SPECIALPRODUCT,
        SUM(sml.C_QUANTITY) AS QtyMove,
        MAX(sm.C_DATE) AS LastDate,
        sl.C_BRANCH AS BranchID
    FROM [dbo].[T_STOCKMOVEMENT_LINE] AS sml WITH (NOLOCK)
    LEFT OUTER JOIN [dbo].[T_STOCKMOVEMENT] AS sm WITH (NOLOCK) ON sm.C_ID = sml.C__OWNER_
    LEFT OUTER JOIN [dbo].[T_STOCKBIN] AS sb WITH (NOLOCK) ON sb.c_id = sml.C_STOCKBIN 
    LEFT OUTER JOIN [dbo].[T_STOCKLOCATION] AS sl WITH (NOLOCK) ON sl.c_id = sb.C_LOCATION
    WHERE sml.C_SPECIALPRODUCT IS NOT NULL 
    GROUP BY sml.C_SPECIALPRODUCT, sl.C_BRANCH
),
SpecialProductPurchasingInfo AS (
    SELECT 
        pp.C_ID AS SpecialProductID,
        cur.C_CODE AS CurrencyCode
    FROM [dbo].[T_SPECIALPRODUCT] sp WITH (NOLOCK)
    LEFT OUTER JOIN [dbo].[T_PRODUCT_PURCHASING] pp WITH (NOLOCK) ON pp.C_ID = sp.C_PURCHASING
    LEFT OUTER JOIN [dbo].[T_CURRENCY] cur WITH (NOLOCK) ON cur.C_ID = pp.C_LISTPRICECURRENCY
)
SELECT 
    sp.C_ID AS SpecialProductID,
    sp.C_STATUS AS ProductStatus,
    sp.C_CODE AS ProductCode,
    sp.C_DESCRIPTION AS ProductDescription,
    PD.C_DESCRIPTION AS Department,
    b.C_CODE AS BranchCode,
    b.C_ID AS BranchID,
    
    -- Stock and movement metrics
    CONVERT(DOUBLE PRECISION, sp.C_STOCKLEVEL) AS IQStockLevel,
    CONVERT(DOUBLE PRECISION, s.Direct) AS SalesDirect,
    CONVERT(DOUBLE PRECISION, po.Direct) AS PODirect,
    CONVERT(DOUBLE PRECISION, s.QTYSupplied) AS SalesQtySupplied,
    CONVERT(DOUBLE PRECISION, po.QTYSupplied) AS POQtySupplied,
    CONVERT(DOUBLE PRECISION, s.QTYOustanding) AS SalesQtyOutstanding,
    CONVERT(DOUBLE PRECISION, po.QTYOustanding) AS POQtyOutstanding,
    
    -- Credit notes and returns
    CONVERT(DOUBLE PRECISION, cr.Direct_QTY_CR) AS DirectQtyCR,
    CONVERT(DOUBLE PRECISION, cr.QTY_CR) AS QtyCR,
    CONVERT(DOUBLE PRECISION, crn.Direct_QTY_CN) AS DirectQtyCN,
    CONVERT(DOUBLE PRECISION, crn.QTY_CN) AS QtyCN,
    CONVERT(DOUBLE PRECISION, pr.Direct_QTY_PR) AS DirectQtyPR,
    CONVERT(DOUBLE PRECISION, pr.QTY_PR) AS QtyPR,
    
    -- Stock movement & frustration
    CONVERT(DOUBLE PRECISION, Smove.QtyMove) AS QtyMove,
    Smove.LastDate AS LastMovementDate,
    CAST(Smove.QtyMove AS INT) - CAST(ISNULL(s.QTYOustanding, 0) AS INT) AS FrustratedStock,
    
    
    u.C_NAME AS CreatedBy,
    sppi.CurrencyCode,
    sp.C_LISTPRICE AS ListPrice,
    sp.C_COSTPRICE AS CostPrice
 

FROM [dbo].[T_SPECIALPRODUCT] AS sp WITH (NOLOCK)
CROSS JOIN [dbo].[T_BRANCH] AS b WITH (NOLOCK)
LEFT OUTER JOIN sales AS s WITH (NOLOCK) ON s.c_id = sp.C_ID AND b.C_ID = s.BranchID
LEFT OUTER JOIN PO AS po ON po.c_id = sp.C_ID AND po.BranchID = b.C_ID
LEFT OUTER JOIN CR AS cr ON cr.c_id = sp.C_ID AND cr.BranchID = b.C_ID
LEFT OUTER JOIN CRN AS crn ON crn.c_id = sp.C_ID AND crn.BranchID = b.C_ID
LEFT OUTER JOIN PR AS pr ON pr.c_id = sp.C_ID AND pr.BranchID = b.C_ID
LEFT OUTER JOIN Smove ON Smove.C_SPECIALPRODUCT = sp.C_ID AND Smove.BranchID = b.C_ID
LEFT OUTER JOIN [dbo].[T_USER] AS u WITH (NOLOCK) ON u.C_ID = sp.C_D_CREATEDBY
LEFT OUTER JOIN [dbo].[T_PRODUCT] AS p WITH (NOLOCK) ON p.C_ID = sp.C_CONVERTEDTOPRODUCT
LEFT OUTER JOIN [dbo].[T_PRODUCTDEPARTMENT] AS PD WITH (NOLOCK) ON PD.C_ID = p.C_DEPARTMENT
LEFT OUTER JOIN [dbo].[T_PRODUCTDEPARTMENTGROUP] AS PDG WITH (NOLOCK) ON PD.C_GROUP = PDG.C_ID
LEFT OUTER JOIN SpecialProductPurchasingInfo AS sppi ON sppi.SpecialProductID = sp.C_ID
WHERE 1=1 
 -- AND PDG.C_CODE = 'AQUAI'
  AND Smove.QtyMove <> 0
  --AND b.C_CODE = 'ROW';
